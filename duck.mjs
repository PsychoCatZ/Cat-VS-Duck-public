export function demo(turn) {
  const count = (turn.score?.cat ?? 0) + (turn.score?.duck ?? 0)
  const parsed = Number(turn.memory)
  const position = Number.isSafeInteger(parsed) && parsed >= 0 && parsed < Number.MAX_SAFE_INTEGER ? parsed : 0
  let [reply, emotion] = demoReplies[position % demoReplies.length]
  if (turn.kind === 'opening') [reply, emotion] = [demoReplies.at(-1)[0], 'neutral']
  if (turn.kind === 'initiative') [reply, emotion] = [demoTopics[position % demoTopics.length], 'joy']
  return normalize({ reply, emotion, intensity: 0.75, winner: count % 3 === 2 ? 'cat' : 'duck',
    memory: String(position + (turn.kind === 'opening' ? 0 : 1)) }, turn)
}
