export function normalize(data, turn) {
  if (typeof data?.reply !== 'string' || !data.reply.trim()) throw new Error('Empty reply')
  return {
    reply: data.reply.trim().slice(0, 1000),
    emotion: Object.hasOwn(emotions, data.emotion) ? data.emotion : 'neutral',
    intensity: Number.isFinite(data.intensity) ? Math.max(0, Math.min(1, data.intensity)) : 0.5,
    winner: turn.score && turn.kind === 'reply' && ['cat', 'duck'].includes(data.winner) ? data.winner : null,
    memory: typeof data.memory === 'string' && data.memory.trim() ? data.memory.slice(0, 900) : turn.memory,
  }
}

